-- Demandes d'ajout de marque / modèle
CREATE TABLE IF NOT EXISTS demandes (
    id INT AUTO_INCREMENT PRIMARY KEY,
    user_id INT NOT NULL,
    type_demande ENUM('nouvelle_marque', 'nouveau_modele') NOT NULL,
    marque_existante VARCHAR(150) NULL,
    nouvelle_marque VARCHAR(150) NULL,
    type_technique VARCHAR(150) NULL,
    nom_modele VARCHAR(150) NOT NULL,
    genre VARCHAR(100) NULL,
    places INT NULL,
    energie VARCHAR(50) NULL,
    puissance VARCHAR(50) NULL,
    ptac VARCHAR(50) NULL,
    statut ENUM('En attente', 'En cours', 'Traité', 'Rejeté') NOT NULL DEFAULT 'En attente',
    motif_rejet TEXT NULL,
    relance_count INT NOT NULL DEFAULT 0,
    last_relance_at TIMESTAMP NULL,
    created_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMP DEFAULT CURRENT_TIMESTAMP ON UPDATE CURRENT_TIMESTAMP,
    CONSTRAINT fk_demandes_user FOREIGN KEY (user_id) REFERENCES users(id) ON DELETE CASCADE
) ENGINE=InnoDB;

